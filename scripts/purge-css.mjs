#!/usr/bin/env node
/**
 * PERF (2026-11-04): generate purged CSS for Tabler core + Tabler icons.
 *
 * The app imports the FULL Tabler core CSS (~536KB) and the FULL Tabler
 * icons webfont CSS (~241KB, ~5.900 icons) while using a fraction of both.
 * This script scans every template (inline TS templates + .html files) for
 * class names and writes trimmed files:
 *
 *   src/styles/tabler.purged.css        <- imported by src/styles.css
 *   src/styles/tabler-icons.purged.css  <- listed in angular.json styles
 *
 * It runs automatically as part of `npm run build` (see package.json), and
 * the generated files are also committed so a bare `ng build` still works.
 * Re-run manually with: npm run purge-css
 *
 * Safety rails:
 * - No class name is built by string concatenation in this codebase
 *   (verified by grep), so static scanning sees every used class.
 * - The safelist keeps runtime/state classes that never appear literally in
 *   templates: Angular form state (ng-*), Bootstrap interaction states
 *   (show/fade/collapse/active/disabled), overlay components (modal,
 *   dropdown, tooltip, popover, toast, offcanvas), form validation and
 *   dark-theme selectors.
 * - @keyframes, @font-face and CSS variables are kept (PurgeCSS defaults),
 *   because Tabler's theming is variable-driven.
 */
import { PurgeCSS } from "purgecss";
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function collectContentFiles(dir, exts, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      collectContentFiles(full, exts, out);
    } else if (exts.some((ext) => entry.endsWith(ext))) {
      out.push(full);
    }
  }
  return out;
}

const contentFiles = [
  ...collectContentFiles(join(root, "src"), [".ts", ".html"]),
];

const safelist = {
  standard: [
    /^ng-/,
    /^cdk-/,
    /^(modal|dropdown|tooltip|popover|toast|offcanvas|carousel)/,
    /(^|[-_])show$/,
    /showing/,
    /hiding/,
    /^collaps/,
    /^fade/,
    /(^|[-_])active$/,
    /(^|[-_])disabled$/,
    /^is-(in)?valid/,
    /was-validated/,
    /data-bs-theme/,
    /spinner/,
    /visually-hidden/,
  ],
  deep: [/modal/, /dropdown/, /tooltip/, /popover/, /offcanvas/, /toast/],
  greedy: [/show/, /fade/, /active/],
};

const extractor = (content) => content.match(/[\w-/:]+(?<!:)/g) || [];

async function purgeOne({ input, output, transform }) {
  const css = readFileSync(input, "utf8");
  const [result] = await new PurgeCSS().purge({
    content: contentFiles,
    css: [{ raw: css, name: input }],
    defaultExtractor: extractor,
    safelist,
  });
  let purged = result.css;
  if (transform) purged = transform(purged);
  const header =
    "/* GENERATED by scripts/purge-css.mjs — do not edit by hand.\n" +
    "   Regenerated on every `npm run build`; source templates are the input. */\n";
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, header + purged);
  const pct = ((1 - purged.length / css.length) * 100).toFixed(1);
  console.log(
    `[purge-css] ${input.split("/").pop()}: ${css.length} -> ${purged.length} bytes (-${pct}%)`,
  );
}

await purgeOne({
  input: join(root, "node_modules/@tabler/core/dist/css/tabler.min.css"),
  output: join(root, "src/styles/tabler.purged.css"),
});

await purgeOne({
  input: join(root, "node_modules/@tabler/icons-webfont/dist/tabler-icons.min.css"),
  output: join(root, "src/styles/tabler-icons.purged.css"),
  // The generated file lives in src/styles/, so font URLs must be rewritten
  // from the package-relative "./fonts/" to the node_modules location; the
  // Angular builder resolves them and emits the font files as assets.
  transform: (css) =>
    css.replaceAll(
      'url("./fonts/',
      'url("../../node_modules/@tabler/icons-webfont/dist/fonts/',
    ),
});
